//! `cargo xtask gen-isolation-commands` and `check-isolation-commands`
//! (plan E7.1, roadmap 3.3: Tauri's isolation pattern).
//!
//! The isolation app (`dist-isolation/`) sees every IPC message before Tauri
//! decrypts it in Rust, and passes one through only when its `cmd` is in
//! `dist-isolation/commands.js`. That list is generated, never edited, from
//! the two places that already decide what a window may call:
//! - every entry of `src-tauri/src/invoke.rs`'s domain lists (the parser
//!   `build.rs` and `tests/capability_policy.rs` share), and
//! - every plugin command a capability file grants by name (release and
//!   debug grants)
//!   (`core:window:allow-minimize` is `plugin:window|minimize`, Tauri's
//!   `plugin:{name}|{command}` form),
//!
//! plus Tauri's own channel fetch, `plugin:__TAURI_CHANNEL__|fetch`
//! (`tauri` 2.12.1 `src/ipc/channel.rs:31`): a `tauri::ipc::Channel` message
//! over its direct-eval threshold is fetched by an invoke the page makes
//! (`channel.rs:319`), so it passes the hook too. The check fails when the
//! file on disk differs from what the generator writes now, so a command
//! added to `invoke.rs` or a grant added to a capability cannot drift from
//! the hook's list.

use std::collections::BTreeSet;
use std::path::Path;

use anyhow::{anyhow, Context, Result};

#[path = "../../src-tauri/build_support/invoke_commands.rs"]
mod invoke_commands;

const INVOKE: &str = "src-tauri/src/invoke.rs";
/// The release grants and the debug-only ones (`invoke.rs`'s debug-gated
/// commands are in the list too: one isolation app serves both builds, and a
/// command a release build does not register is refused by Rust anyway).
const CAPABILITIES: [&str; 2] = ["src-tauri/capabilities", "src-tauri/capabilities-dev"];
const OUT: &str = "dist-isolation/commands.js";

/// Tauri's channel-fetch command (`tauri::ipc::channel::FETCH_CHANNEL_DATA_COMMAND`).
const CHANNEL_FETCH: &str = "plugin:__TAURI_CHANNEL__|fetch";

/// The plugin command a granted permission names, or `None` for an app
/// command's own `allow-{command}` (those come from `invoke.rs`). A grant
/// that names no single command (a `default` bundle, a `deny-`) is refused:
/// the hook could not tell which commands it opens.
fn plugin_command(permission: &str) -> Result<Option<String>> {
    let Some((scope, name)) = permission.rsplit_once(':') else {
        return Ok(None);
    };
    let plugin = scope.strip_prefix("core:").unwrap_or(scope);
    let command = name.strip_prefix("allow-").ok_or_else(|| {
        anyhow!(
            "capability grant `{permission}` names no single command (`<plugin>:allow-<command>`)"
        )
    })?;
    Ok(Some(format!(
        "plugin:{plugin}|{}",
        command.replace('-', "_")
    )))
}

/// Every command the isolation hook passes, sorted.
fn commands(root: &Path) -> Result<BTreeSet<String>> {
    let src =
        std::fs::read_to_string(root.join(INVOKE)).with_context(|| format!("reading {INVOKE}"))?;
    let mut out: BTreeSet<String> = invoke_commands::parse(&src)
        .map_err(|e| anyhow!("{INVOKE}: {e}"))?
        .iter()
        .map(|c| c.name().to_owned())
        .collect();
    let mut files = Vec::new();
    for dir in CAPABILITIES {
        for entry in std::fs::read_dir(root.join(dir)).with_context(|| format!("reading {dir}"))? {
            files.push(entry?.path());
        }
    }
    files.retain(|p| p.extension().is_some_and(|x| x == "json"));
    files.sort();
    for path in files {
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        let doc: serde_json::Value =
            serde_json::from_str(&text).with_context(|| format!("parsing {}", path.display()))?;
        let grants = doc["permissions"]
            .as_array()
            .ok_or_else(|| anyhow!("{} has no `permissions` array", path.display()))?;
        for grant in grants {
            let grant = grant
                .as_str()
                .ok_or_else(|| anyhow!("{}: a grant is not a string", path.display()))?;
            if let Some(cmd) = plugin_command(grant).with_context(|| path.display().to_string())? {
                out.insert(cmd);
            }
        }
    }
    out.insert(CHANNEL_FETCH.to_owned());
    Ok(out)
}

/// `dist-isolation/commands.js` for `commands`: one top-level `const` the
/// isolation app's `index.js` reads (Tauri inlines both scripts into the
/// isolation page, `tauri-utils` `html2::inline_isolation`, and the page's
/// CSP is `default-src 'none'`, so the list cannot be fetched as JSON).
fn render(commands: &BTreeSet<String>) -> Result<String> {
    let list = serde_json::to_string_pretty(&commands.iter().collect::<Vec<_>>())?;
    Ok(format!(
        "// Generated by `cargo xtask gen-isolation-commands` from src-tauri/src/invoke.rs and\n\
         // the capability grants; do not edit. `cargo xtask check` fails when it is stale.\n\
         const REKINDLE_ISOLATION_COMMANDS = Object.freeze({list});\n"
    ))
}

/// Writes `dist-isolation/commands.js`.
pub fn gen_isolation_commands(root: &Path) -> Result<()> {
    let content = render(&commands(root)?)?;
    std::fs::write(root.join(OUT), content).with_context(|| format!("writing {OUT}"))?;
    println!("    wrote {OUT}");
    Ok(())
}

/// Fails when `dist-isolation/commands.js` is not what the generator writes now.
pub fn check_isolation_commands(root: &Path) -> Result<()> {
    let want = render(&commands(root)?)?;
    match std::fs::read_to_string(root.join(OUT)) {
        Ok(on_disk) if on_disk == want => Ok(()),
        Ok(_) => Err(anyhow!(
            "{OUT}: stale (a command or a capability grant changed). Run `cargo xtask gen-isolation-commands`."
        )),
        Err(e) => Err(anyhow!("{OUT}: {e}. Run `cargo xtask gen-isolation-commands`.")),
    }
}

