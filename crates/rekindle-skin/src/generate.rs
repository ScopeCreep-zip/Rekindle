/// An opaline theme (`load_from_str`) of the registry's colours on `base`
/// (`Dark` or `Light`), for the TUI.
#[must_use]
pub fn tui_palette(base: Base) -> String {
    let (name, variant) = match base {
        Base::Light | Base::HcLight => ("Rekindle Light", "light"),
        Base::Dark | Base::HcDark => ("Rekindle Dark", "dark"),
    };
    let values: BTreeMap<&str, String> = defaults(base)
        .iter()
        .filter_map(|(e, v)| css_value(e, v).map(|c| (e.id, c)))
        .collect();
    let mut out = format!(
        "# {HEADER}\n\n[meta]\nname = \"{name}\"\nauthor = \"Rekindle\"\nvariant = \"{variant}\"\nversion = \"1\"\ndescription = \"The skin registry's {variant} defaults\"\n\n[tokens]\n"
    );
    for (role, id) in TUI_TOKENS {
        if let Some(hex) = values.get(id) {
            let _ = writeln!(out, "\"{role}\" = \"{hex}\"");
        }
    }
    out.push('\n');
    out.push_str(TUI_STYLES);
    out
}

fn value_schema(ty: TokenType) -> Value {
    let alias = json!({ "type": "string", "pattern": "^\\{[a-z0-9-]+(\\.[a-z0-9-]+)*\\}$" });
    let concrete = match ty {
        TokenType::Color => json!({ "oneOf": [
            { "type": "string", "pattern": "^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$" },
            { "type": "object", "additionalProperties": false, "required": ["colorSpace", "components"],
              "properties": {
                "colorSpace": { "const": "srgb" },
                "components": { "type": "array", "minItems": 3, "maxItems": 3,
                                "items": { "type": "number", "minimum": 0, "maximum": 1 } },
                "alpha": { "type": "number", "minimum": 0, "maximum": 1 },
                "hex": { "type": "string", "pattern": "^#[0-9a-fA-F]{6}$" } } } ] }),
        TokenType::Dimension { min, max } => json!({
            "type": "object", "additionalProperties": false, "required": ["value", "unit"],
            "properties": { "value": { "type": "integer", "minimum": min, "maximum": max },
                            "unit": { "const": "px" } } }),
        TokenType::Number { .. } => json!({ "type": "number", "multipleOf": 0.001 }),
        TokenType::FontFamily => {
            json!({ "enum": FONTS.iter().map(|f| f.name).collect::<Vec<_>>() })
        }
    };
    json!({ "oneOf": [concrete, alias] })
}

fn meta_properties(props: &mut Map<String, Value>) {
    props.insert(
        "$type".into(),
        json!({ "enum": ["color", "dimension", "number", "fontFamily"] }),
    );
    props.insert(
        "$description".into(),
        json!({ "type": "string", "maxLength": 280 }),
    );
    props.insert(
        "$extensions".into(),
        json!({ "type": "object", "additionalProperties": false,
                "properties": { EXTENSIONS_NAMESPACE: { "type": "object", "maxProperties": 0 } } }),
    );
}

/// Inserts `e` at its dotted path under `node`, a group schema.
fn insert(node: &mut Value, path: &[&str], e: &TokenEntry) {
    let props = node["properties"]
        .as_object_mut()
        .expect("every group schema has properties");
    let Some((head, rest)) = path.split_first() else {
        return;
    };
    if rest.is_empty() {
        let mut p = Map::new();
        meta_properties(&mut p);
        p.insert("$type".into(), json!({ "const": e.ty.dtcg() }));
        p.insert("$value".into(), value_schema(e.ty));
        props.insert(
            (*head).to_owned(),
            json!({ "type": "object", "additionalProperties": false, "required": ["$value"], "properties": p }),
        );
        return;
    }
    let child = props.entry((*head).to_owned()).or_insert_with(group);
    insert(child, rest, e);
}

fn group() -> Value {
    let mut p = Map::new();
    meta_properties(&mut p);
    json!({ "type": "object", "additionalProperties": false, "properties": p })
}

/// The JSON Schema of a skin token file: every themeable id, typed.
#[must_use]
pub fn json_schema() -> String {
    let mut root = group();
    for e in ENTRIES.iter().filter(|e| e.class == Class::Themeable) {
        let path: Vec<&str> = e.id.split('.').collect();
        insert(&mut root, &path, e);
    }
    root["$schema"] = json!("https://json-schema.org/draft/2020-12/schema");
    root["title"] = json!("A rekindle-skin/1 token file");
    root["$comment"] = json!(HEADER);
    root["description"] = json!(
        "A variant's token file (restricted DTCG 2025.10): every themeable id of the closed \
         registry, typed; unknown keys are refused."
    );
    let mut s = serde_json::to_string_pretty(&root).expect("a JSON value serialises");
    s.push('\n');
    s
}
