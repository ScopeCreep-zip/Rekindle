//! The registry's generated artefacts (plan E7.7.1), written by `cargo
//! xtask gen-skin-registry` and checked for staleness by `cargo xtask
//! check`: the app's token CSS, the TS types, the TUI palettes and the JSON
//! Schema of a token file. Every value is re-emitted from the registry's
//! numbers ([`crate::tokens::emit`]).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::{json, Map, Value};

use crate::registry::{resolve, Base, Class, TokenEntry, TokenType, ENTRIES, FONTS};
use crate::tokens::emit::{css_value, declarations};
use crate::tokens::EXTENSIONS_NAMESPACE;

const HEADER: &str = "Generated by `cargo xtask gen-skin-registry` from `rekindle-skin::registry` \
(plan E7.7.1). Do not edit: change the registry and regenerate; `cargo xtask check` fails \
when this file is stale.";

/// The defaults of `base`, in table order.
fn defaults(base: Base) -> Vec<(&'static TokenEntry, rekindle_types::dto::skin::TokenValue)> {
    resolve(ENTRIES, base, &BTreeMap::new())
}

fn css_syntax(ty: TokenType) -> Option<&'static str> {
    match ty {
        TokenType::Color => Some("<color>"),
        TokenType::Dimension { .. } => Some("<length>"),
        TokenType::Number { .. } => Some("<number>"),
        TokenType::FontFamily => None,
    }
}

/// `src/styles/generated/tokens.css`: `@property` registrations of the
/// typed tokens, the dark defaults as Tailwind 4 `@theme`, and the light
/// values that differ, in `@layer xfire-defaults`.
///
/// # Panics
/// Never for the shipped registry (its defaults fit their types, which
/// this crate's tests check).
#[must_use]
pub fn tokens_css() -> String {
    let dark = defaults(Base::Dark);
    let light = defaults(Base::Light);
    let mut out = format!("/* {HEADER}\n *\n * The dark defaults are `@theme`; the light base revalues\n * what differs under `:root[data-skin-base=\"light\"]` (E7.7.2's apply\n * step sets the attribute). */\n");
    for (e, v) in &dark {
        let (Some(syntax), Some(value)) = (css_syntax(e.ty), css_value(e, v)) else {
            continue;
        };
        let _ = write!(
            out,
            "@property {} {{\n  syntax: \"{syntax}\";\n  inherits: true;\n  initial-value: {value};\n}}\n",
            e.css
        );
    }
    let theme = declarations(&dark, 2).expect("registry defaults fit their types");
    let _ = write!(out, "\n@theme {{\n{theme}}}\n");
    let differ: Vec<_> = light
        .into_iter()
        .zip(&dark)
        .filter(|((_, l), (_, d))| l != d)
        .map(|(l, _)| l)
        .collect();
    let light_decls = declarations(&differ, 4).expect("registry defaults fit their types");
    let _ = write!(
        out,
        "\n@layer xfire-defaults {{\n  :root[data-skin-base=\"light\"] {{\n{light_decls}  }}\n}}\n"
    );
    out
}

/// `src/styles/generated/tokens.ts`: the registry ids as a TS type and a
/// typed `var(--…)` accessor.
#[must_use]
pub fn tokens_ts() -> String {
    let mut out = format!("// {HEADER}\n\n/** A token id of the closed skin registry. */\nexport type SkinTokenId =\n");
    for e in ENTRIES {
        let _ = writeln!(out, "  | \"{}\"", e.id);
    }
    out.push_str(";\n\nconst CSS_PROPERTY: Readonly<Record<SkinTokenId, string>> = {\n");
    for e in ENTRIES {
        let _ = writeln!(out, "  \"{}\": \"{}\",", e.id, e.css);
    }
    out.push_str(
        "};\n\n/** `var(--…)` of a registry token, for inline custom properties. */\n\
         export function tokenVar(id: SkinTokenId): string {\n  return `var(${CSS_PROPERTY[id]})`;\n}\n",
    );
    out
}

