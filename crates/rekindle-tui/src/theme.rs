//! Theme integration via opaline.
//!
//! Wraps [`opaline::Theme`] with rekindle-specific token extensions
//! and glyph fallback for accessibility.

use std::fmt::Write as _;

use ratatui::style::{Color, Style};
use ratatui::text::Span;
use rekindle_types::dto::skin::SkinBase;
use rekindle_types::dto::skin_library::{SkinApplied, SkinPaletteColour};

use crate::colour_depth::ColourDepth;

/// Theme manager wrapping opaline with app-specific extensions.
pub struct ThemeManager {
    theme: opaline::Theme,
    name: String,
    use_unicode: bool,
    depth: ColourDepth,
}

/// The skin registry's palettes (plan E7.7.1), generated by `cargo xtask
/// gen-skin-registry` and fed to opaline through `load_from_str`: the TUI
/// shows the same defaults as the app.
const REGISTRY_THEMES: &[(&str, &str)] = &[
    (
        "rekindle-dark",
        include_str!("../themes/rekindle-dark.toml"),
    ),
    (
        "rekindle-light",
        include_str!("../themes/rekindle-light.toml"),
    ),
];

/// A registry palette by name, else an opaline builtin or user theme.
fn load_theme(name: &str) -> anyhow::Result<opaline::Theme> {
    if let Some((_, toml)) = REGISTRY_THEMES.iter().find(|(n, _)| *n == name) {
        return opaline::load_from_str(toml, None)
            .map_err(|e| anyhow::anyhow!("theme '{name}' does not load: {e}"));
    }
    opaline::load_by_name(name).ok_or_else(|| anyhow::anyhow!("theme '{name}' not found"))
}

/// The registry palette of `base`, whose roles and styles a skin's palette
/// revalues.
fn registry_toml(base: SkinBase) -> &'static str {
    let name = match base {
        SkinBase::Dark => "rekindle-dark",
        SkinBase::Light => "rekindle-light",
    };
    REGISTRY_THEMES
        .iter()
        .find(|(n, _)| *n == name)
        .map_or("", |(_, toml)| toml)
}

/// The opaline theme of a skin's palette (plan E7.7.2: the TUI applies the
/// palette subset the Host serves in `SkinApplied`, never CSS): the
/// registry palette of the skin's base with its `[tokens]` replaced by the
/// skin's colours, so every style resolves from them. A role the registry
/// does not name, a missing one or a repeated one is refused.
fn skin_theme(base: SkinBase, palette: &[SkinPaletteColour]) -> anyhow::Result<opaline::Theme> {
    let toml = registry_toml(base);
    let (head, rest) = toml
        .split_once("\n[tokens]\n")
        .ok_or_else(|| anyhow::anyhow!("the registry palette has no [tokens]"))?;
    let (roles, styles) = rest
        .split_once("\n[styles]\n")
        .ok_or_else(|| anyhow::anyhow!("the registry palette has no [styles]"))?;
    let known: Vec<&str> = roles.lines().filter_map(|l| l.split('"').nth(1)).collect();
    let mut tokens = String::new();
    let mut seen = Vec::with_capacity(palette.len());
    for c in palette {
        let role = c.role.as_str();
        if !known.contains(&role) || seen.contains(&role) {
            anyhow::bail!("skin palette role '{role}' is not a TUI role or repeats");
        }
        seen.push(role);
        let [r, g, b] = c.rgb;
        let _ = writeln!(tokens, "\"{role}\" = \"#{r:02x}{g:02x}{b:02x}\"");
    }
    if seen.len() != known.len() {
        anyhow::bail!(
            "skin palette names {} of {} TUI roles",
            seen.len(),
            known.len()
        );
    }
    let themed = format!("{head}\n[tokens]\n{tokens}\n[styles]\n{styles}");
    opaline::load_from_str(&themed, None)
        .map_err(|e| anyhow::anyhow!("skin palette does not load: {e}"))
}

impl ThemeManager {
    /// Load a theme by name: a skin registry palette (`rekindle-dark`,
    /// `rekindle-light`), an opaline builtin or a user theme.
    pub fn load(name: &str) -> anyhow::Result<Self> {
        let theme = load_theme(name)?;
        let use_unicode = rekindle_client::term::use_unicode();
        Ok(Self {
            theme,
            name: name.to_string(),
            use_unicode,
            depth: ColourDepth::detect(),
        })
    }

    /// Show the skin the Host resolved (`SkinGet` at start, then every
    /// `SystemEvent::SkinChanged`): its palette on its base. On a refused
    /// palette the theme shown is kept.
    pub fn apply_skin(&mut self, skin: &SkinApplied) -> anyhow::Result<()> {
        self.theme = skin_theme(skin.base, &skin.palette)?;
        self.name.clone_from(&skin.id);
        Ok(())
    }

    /// Follow the Host's stream: `SkinChanged` applies its skin (`Some`
    /// with the outcome); every other event is not the theme's (`None`).
    pub fn on_event(
        &mut self,
        event: &rekindle_types::subscription_events::SubscriptionEvent,
    ) -> Option<anyhow::Result<()>> {
        use rekindle_types::subscription_events::{SubscriptionEvent, SystemEvent};
        match event {
            SubscriptionEvent::System(SystemEvent::SkinChanged { skin }) => {
                Some(self.apply_skin(skin))
            }
            _ => None,
        }
    }

    /// Semantic color accessor — returns ratatui Color at the terminal's
    /// colour depth.
    pub fn color(&self, token: &str) -> Color {
        self.depth.fit(self.theme.color(token).into())
    }

    /// Semantic style accessor — returns ratatui Style at the terminal's
    /// colour depth.
    pub fn style(&self, name: &str) -> Style {
        self.depth.fit_style(self.theme.style(name).into())
    }

    /// Create a styled span.
    pub fn span<'a>(&self, style_name: &str, content: &'a str) -> Span<'a> {
        Span::styled(content, self.style(style_name))
    }

    /// Whether this is a light theme.
    pub fn is_light(&self) -> bool {
        self.theme.is_light()
    }

    /// Theme name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Whether Unicode glyphs are available.
    pub fn use_unicode(&self) -> bool {
        self.use_unicode
    }

    /// Status glyph — uses text labels for accessibility.
    pub fn status_glyph(&self, pass: bool) -> &'static str {
        if pass {
            if self.use_unicode {
                "●"
            } else {
                "[OK]"
            }
        } else if self.use_unicode {
            "○"
        } else {
            "[--]"
        }
    }

    /// Focused border style.
    pub fn focused_border(&self) -> Style {
        Style::default().fg(self.color("accent.primary"))
    }

    /// Unfocused border style.
    pub fn unfocused_border(&self) -> Style {
        Style::default().fg(self.color("border.unfocused"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_registry_palettes_load_with_their_values() {
        let dark = load_theme("rekindle-dark").expect("dark palette loads");
        let light = load_theme("rekindle-light").expect("light palette loads");
        assert!(!dark.is_light());
        assert!(light.is_light());
        assert_eq!(
            Color::from(dark.color("text.primary")),
            Color::Rgb(0xe7, 0xe7, 0xe7)
        );
        assert_eq!(
            Color::from(light.color("text.primary")),
            Color::Rgb(0x1a, 0x1a, 0x1a)
        );
    }

    /// Every TUI role of the dark registry palette, at `rgb`, but
    /// `accent.primary` at `accent`.
    fn palette(rgb: [u8; 3], accent: [u8; 3]) -> Vec<SkinPaletteColour> {
        let roles: Vec<String> = registry_toml(SkinBase::Dark)
            .split_once("\n[tokens]\n")
            .and_then(|(_, r)| r.split_once("\n[styles]\n"))
            .map(|(r, _)| {
                r.lines()
                    .filter_map(|l| l.split('"').nth(1))
                    .map(str::to_owned)
                    .collect()
            })
            .expect("the registry palette has roles");
        roles
            .into_iter()
            .map(|role| SkinPaletteColour {
                rgb: if role == "accent.primary" {
                    accent
                } else {
                    rgb
                },
                role,
            })
            .collect()
    }

    fn skin(base: SkinBase, palette: Vec<SkinPaletteColour>) -> SkinApplied {
        SkinApplied {
            id: "pkg:0123".into(),
            base,
            tokens_href: String::new(),
            regions: Vec::new(),
            palette,
        }
    }

    #[test]
    fn a_skin_palette_becomes_the_tui_theme_colours() {
        let mut t = ThemeManager::load("rekindle-dark").expect("dark loads");
        t.depth = ColourDepth::TrueColour;
        let before = t.color("accent.primary");
        assert_eq!(before, Color::Rgb(0x34, 0x91, 0xd8));
        t.apply_skin(&skin(
            SkinBase::Light,
            palette([0x10, 0x20, 0x30], [0xaa, 0xbb, 0xcc]),
        ))
        .expect("the palette applies");
        assert_eq!(t.color("accent.primary"), Color::Rgb(0xaa, 0xbb, 0xcc));
        assert_eq!(t.color("text.primary"), Color::Rgb(0x10, 0x20, 0x30));
        // The styles resolve from the skin's colours, and its base is kept.
        assert_eq!(t.focused_border().fg, Some(Color::Rgb(0xaa, 0xbb, 0xcc)));
        assert_eq!(t.style("keyword").fg, Some(Color::Rgb(0xaa, 0xbb, 0xcc)));
        assert!(t.is_light());
        assert_eq!(t.name(), "pkg:0123");
        t.depth = ColourDepth::Ansi256;
        assert_eq!(t.color("accent.primary"), Color::Indexed(146));
    }

    #[test]
    fn a_skin_changed_event_swaps_the_theme() {
        use rekindle_types::subscription_events::{SubscriptionEvent, SystemEvent};
        let mut t = ThemeManager::load("rekindle-dark").expect("dark loads");
        t.depth = ColourDepth::TrueColour;
        let other = SubscriptionEvent::System(SystemEvent::AuditChainBroken { cursor: 1 });
        assert!(t.on_event(&other).is_none());
        let changed = SubscriptionEvent::System(SystemEvent::SkinChanged {
            skin: skin(SkinBase::Dark, palette([9, 9, 9], [0x51, 0xe3, 0x85])),
        });
        assert!(matches!(t.on_event(&changed), Some(Ok(()))));
        assert_eq!(t.color("accent.primary"), Color::Rgb(0x51, 0xe3, 0x85));
        assert_eq!(t.unfocused_border().fg, Some(Color::Rgb(9, 9, 9)));
    }

    #[test]
    fn a_palette_with_a_stray_or_missing_role_is_refused_and_the_theme_kept() {
        let mut t = ThemeManager::load("rekindle-dark").expect("dark loads");
        let mut stray = palette([1, 2, 3], [4, 5, 6]);
        stray[0].role = "x\" = \"#000000".into();
        assert!(t.apply_skin(&skin(SkinBase::Dark, stray)).is_err());
        let mut short = palette([1, 2, 3], [4, 5, 6]);
        short.pop();
        assert!(t.apply_skin(&skin(SkinBase::Dark, short)).is_err());
        assert_eq!(t.name(), "rekindle-dark");
        assert!(!t.is_light());
    }
}
