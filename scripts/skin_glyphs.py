#!/usr/bin/env python3
"""Write src/components/common/glyph_art.ts: the shell's own icon set (plan
SK17-7a), the outlines of the Material Design Icons glyphs the app used
through Symbols Nerd Font Mono, as SVG path data.

A skinned window draws these as inline SVG in the role's colour, never as a
font glyph. Each glyph keeps the font's em square (units per em, flipped at
the ascent), so at 1em it sits where and at the size the font glyph did.

Source: src/assets/fonts/SymbolsNerdFontMono-Regular.woff2 (its name and
version are read from the font and recorded in src/assets/icons/NOTICE.md);
the codepoints are src/icons.ts's constants. The glyphs are Material Design
Icons by Pictogrammers, Apache License 2.0 (src/assets/icons/).

Usage (fontTools with brotli): python3 scripts/skin_glyphs.py
"""

import re
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "src/assets/fonts/SymbolsNerdFontMono-Regular.woff2"
ICONS = ROOT / "src/icons.ts"
OUT = ROOT / "src/components/common/glyph_art.ts"
NOTICE = ROOT / "src/assets/icons/NOTICE.md"

# Glyph name -> src/icons.ts constant. The Community window's roles use the
# Host's names (community_icon, src/styles/generated/community_icon.ts); the
# rest are the shell's own.
GLYPHS = {
    "voice.server": "ICON_VOLUME_HIGH",
    "mic.on": "ICON_MIC",
    "mic.off": "ICON_MIC_OFF",
    "speaker.on": "ICON_HEADPHONES",
    "speaker.muted": "ICON_VOLUME_OFF",
    "speaker.off": "ICON_HEADPHONES_OFF",
    "fold.open": "ICON_CHEVRON_DOWN",
    "fold.closed": "ICON_CHEVRON_RIGHT",
    "room": "ICON_COMMUNITIES",
    "chat": "ICON_CHANNEL_TEXT",
    "account-remove": "ICON_ACCOUNT_REMOVE",
    "archive": "ICON_ARCHIVE",
    "arrow-down": "ICON_ARROW_DOWN",
    "arrow-up": "ICON_ARROW_UP",
    "ban": "ICON_BAN",
    "bell": "ICON_BELL",
    "check": "ICON_CHECK",
    "close": "ICON_CLOSE",
    "copy": "ICON_COPY",
    "delete": "ICON_DELETE",
    "folder": "ICON_FOLDER",
    "gamepad": "ICON_GAMEPAD",
    "key": "ICON_KEY",
    "logout": "ICON_LOGOUT",
    "megaphone": "ICON_MEGAPHONE",
    "pencil": "ICON_PENCIL",
    "perms": "ICON_PERMS",
    "phone": "ICON_PHONE",
    "pin": "ICON_PIN",
    "plus": "ICON_PLUS",
    "plus-box": "ICON_PLUS_BOX",
    "refresh": "ICON_REFRESH",
    "save": "ICON_SAVE",
    "search": "ICON_SEARCH",
    "server": "ICON_SERVER",
    "settings": "ICON_SETTINGS",
    "shield": "ICON_SHIELD",
    "thread": "ICON_THREAD",
    "timeout": "ICON_TIMEOUT",
}


def codepoints() -> dict:
    out = {}
    for m in re.finditer(r'export const (ICON_[A-Z0-9_]+) = "\\u\{([0-9A-Fa-f]+)\}"', ICONS.read_text()):
        out[m.group(1)] = int(m.group(2), 16)
    return out


def main() -> int:
    font = TTFont(str(FONT))
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    em = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    cps = codepoints()
    lines = []
    for name, const in GLYPHS.items():
        if const not in cps:
            print(f"{const} is not in src/icons.ts", file=sys.stderr)
            return 1
        glyph = cmap.get(cps[const])
        if glyph is None:
            print(f"{const} U+{cps[const]:X} is not in the font", file=sys.stderr)
            return 1
        pen = SVGPathPen(glyphs)
        # Font units, y up from the baseline -> SVG, y down from the em top.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
        advance = font["hmtx"][glyph][0]
        lines.append(f'  "{name}": {{ x: {(advance - em) // 2}, d: "{pen.getCommands()}" }},')
    family = font["name"].getDebugName(1)
    version = font["name"].getDebugName(5)
    OUT.write_text(
        "// Generated by scripts/skin_glyphs.py from src/assets/fonts/SymbolsNerdFontMono-Regular.woff2\n"
        f"// ({family}, {version}) at src/icons.ts's codepoints. Do not edit: regenerate.\n"
        "// Material Design Icons by Pictogrammers, Apache License 2.0: src/assets/icons/NOTICE.md.\n\n"
        "/** One glyph: its path in the font's em square, and the square's left edge. */\n"
        "export interface GlyphArt {\n  x: number;\n  d: string;\n}\n\n"
        f"/** The em square's side, in font units. */\nexport const GLYPH_EM = {em};\n\n"
        "/** The shell's icon set, by name (plan SK17-7a). */\n"
        "export const GLYPH_ART = {\n" + "\n".join(lines) + "\n} as const satisfies Record<string, GlyphArt>;\n\n"
        "export type GlyphName = keyof typeof GLYPH_ART;\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines)} glyphs")
    NOTICE.write_text(
        "# The shell's icon set\n\n"
        "`src/components/common/glyph_art.ts` holds the SVG outlines of the icons the Community\n"
        "window draws (plan SK17-7a, `SkinGlyph`), written by `scripts/skin_glyphs.py`.\n\n"
        "## Source\n\n"
        f"- Font: **{family}**, `{version}` (the font's own name table), the file\n"
        "  `src/assets/fonts/SymbolsNerdFontMono-Regular.woff2` the app ships\n"
        "- Glyphs: **Material Design Icons** by Pictogrammers (https://pictogrammers.com), as\n"
        "  carried in Nerd Fonts (https://www.nerdfonts.com)\n"
        f"- Icons taken: {len(lines)}, at the codepoints `src/icons.ts` names\n"
        "- Licence: Apache License 2.0, full text in `LICENSE-Apache-2.0.txt` (the canonical\n"
        "  text, sha256 cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30)\n\n"
        "The outlines are copied unchanged, in the font's em square. No font is loaded to draw them.\n"
    )
    print(f"wrote {NOTICE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
